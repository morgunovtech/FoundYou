const I18nContext = createContext<I18nContextValue | undefined>(undefined);

const LANG_STORAGE_KEY = 'meta-data-lang';

export const I18nProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [lang, setLang] = useState<Language>(() => {
    if (typeof window === 'undefined') {
      return 'ru';
    }
    const stored = window.localStorage.getItem(LANG_STORAGE_KEY);
    if (stored === 'ru' || stored === 'en' || stored === 'uz') {
      return stored;
    }
    return 'ru';
  });

  const setLanguage = useCallback((next: Language) => {
    setLang(next);
    if (typeof window !== 'undefined') {
      window.localStorage.setItem(LANG_STORAGE_KEY, next);
    }
  }, []);

  useEffect(() => {
    if (typeof document !== 'undefined') {
      document.documentElement.lang = lang;
    }
  }, [lang]);

  const value = useMemo<I18nContextValue>(() => ({
    lang,
    messages: messages[lang],
    setLanguage
  }), [lang, setLanguage]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
};

export const useI18n = () => {
  const ctx = useContext(I18nContext);
  if (!ctx) {
    throw new Error('useI18n must be used within I18nProvider');
  }
  return ctx;
};

export type MessageKey = keyof typeof messages.ru;

export const useT = () => {
  const { messages: dict } = useI18n();
  return useCallback(
    (key: MessageKey, params?: Record<string, string | number>): string => {
      const template = dict[key];
      // Only a missing key falls back to its name; an empty string is a valid value.
      if (template === undefined) {
        return key;
      }
      if (!params) {
        return template;
      }
      return Object.entries(params).reduce(
        (acc, [paramKey, paramValue]) => acc.replace(`{${paramKey}}`, String(paramValue)),
        template
      );
    },
    [dict]
  );
};

